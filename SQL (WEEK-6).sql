USE ECOMMERCE;

CREATE TABLE REVIEWING
(
    REVIEW_ID INT PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(50),
    PRODUCTID INT,
    REVIEW_TEXT VARCHAR(100),
    REVIEW_DATE DATE
    
    
);

CREATE TABLE RATE
(
    RATING_ID INT PRIMARY KEY,
    REVIEW_ID INT,
    RATING INT,
    FOREIGN KEY(REVIEW_ID)
    REFERENCES REVIEWING(REVIEW_ID)
);

