USE ECOMMERCE;

SELECT ORDERTABLE.ORDER_ID,
       ORDERDETAIL.PRODUCTID,
       ORDERDETAIL.PRODUCT_QUANTITY
FROM ORDERTABLE
INNER JOIN ORDERDETAIL
ON ORDERTABLE.ORDER_ID = ORDERDETAIL.ORDER_ID;

SELECT ORDERTABLE.ORDER_ID,
       ORDERTABLE.CUSTOMER_NAME,
       ORDERDETAIL.PRODUCTID,
       ORDERDETAIL.PRODUCT_QUANTITY
FROM ORDERTABLE
RIGHT JOIN ORDERDETAIL
ON ORDERTABLE.ORDER_ID = ORDERDETAIL.ORDER_ID;

SELECT ORDERTABLE.ORDER_ID,
       ORDERTABLE.TOTAL_PRICE,
       PAYMENT.PAYMENTMODE,
       PAYMENT.PAYMENTAMOUNT
FROM ORDERTABLE
INNER JOIN PAYMENT
ON ORDERTABLE.ORDER_ID = PAYMENT.ORDER_ID;

SELECT ORDERTABLE.ORDER_ID,
       ORDERTABLE.TOTAL_PRICE,
       PAYMENT.PAYMENTMODE,
       PAYMENT.PAYMENTSTATUS
FROM ORDERTABLE
LEFT JOIN PAYMENT
ON ORDERTABLE.ORDER_ID = PAYMENT.ORDER_ID;

SELECT PRODUCT.PRODUCTNAME,
       CATEGORY.CATEGORYNAME
FROM PRODUCT
INNER JOIN CATEGORY
ON PRODUCT.CATEGORYID = CATEGORY.CATEGORYID;

SELECT ORDERTABLE.ORDER_ID,
       PRODUCT.PRODUCTNAME,
       ORDERDETAIL.PRODUCT_QUANTITY,
       PAYMENT.PAYMENTSTATUS
FROM ORDERTABLE
INNER JOIN ORDERDETAIL
ON ORDERTABLE.ORDER_ID = ORDERDETAIL.ORDER_ID
INNER JOIN PRODUCT
ON ORDERDETAIL.PRODUCTID = PRODUCT.PRODUCTID
LEFT JOIN PAYMENT
ON ORDERTABLE.ORDER_ID = PAYMENT.ORDER_ID;